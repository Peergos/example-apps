// Peergos passes one of en-GB, zh-CN, de, el, es, fr, it, ko, nl and pl; a browser's own can be any tag
const LANG = (() => {
	let asked = new URL(window.location.href).searchParams.get('lang') || navigator.language || 'en';
	if (asked.toLowerCase().startsWith('zh'))
		return 'zh-CN';
	let prefix = asked.toLowerCase().split('-')[0];
	return STRINGS[prefix] ? prefix : 'en';
})();

// the text for key, its plural form chosen by count, from the language in use, else English
function template(key, count) {
	let lang = STRINGS[LANG][key] !== undefined ? LANG : 'en';
	let value = STRINGS[lang][key];
	if (value === undefined)
		return key;
	if (typeof value == 'object')
		value = value[new Intl.PluralRules(lang).select(count)] || value.other;
	return value;
}

function fill(text, args) {
	return text.replace(/\{(\d+)\}/g, (m, i) => args[i] !== undefined ? String(args[i]) : m);
}

function t(key, ...args) {
	return fill(template(key, args[0]), args);
}

// the page's own text, marked in index.html with the key it shows
function translatePage() {
	document.documentElement.lang = LANG;
	for (let e of document.querySelectorAll('[data-i18n]'))
		e.textContent = t(e.dataset.i18n);
	for (let e of document.querySelectorAll('[data-i18n-label]')) {
		e.setAttribute('aria-label', t(e.dataset.i18nLabel));
		e.title = t(e.dataset.i18nLabel);
	}
	for (let e of document.querySelectorAll('[data-i18n-aria]'))
		e.setAttribute('aria-label', t(e.dataset.i18nAria));
	for (let e of document.querySelectorAll('[data-i18n-title]'))
		e.title = t(e.dataset.i18nTitle);
	for (let e of document.querySelectorAll('[data-i18n-placeholder]'))
		e.placeholder = t(e.dataset.i18nPlaceholder);
}
